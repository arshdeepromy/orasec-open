"""Generate orasec/templates/orasec/_theme_dark.html from the Tailwind token palette (run from the repo root)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
tw = (ROOT / "orasec/static/orasec/css/tailwind-out.css").read_text()
defs = dict(re.findall(r"(--color-[a-z0-9-]+):\s*([^;}]+)", tw))

STEPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"]
NEUTRAL = dict(zip(STEPS, ["#141d1c", "#1a2423", "#24312f", "#34443f", "#5b6f6a", "#7f938e", "#a1b4af",
                           "#c3d2ce", "#dbe6e3", "#ebf3f1", "#f6faf9"]))
SWAP = {"50": "950", "100": "900", "200": "800", "300": "700", "700": "300", "800": "200", "900": "100", "950": "50"}

v = {}
for fam in ("gray", "slate"):
    for s in STEPS:
        v[f"--color-{fam}-{s}"] = NEUTRAL[s]
for fam in ("red", "green", "yellow", "amber", "blue", "teal"):
    for s, t in SWAP.items():
        if f"--color-{fam}-{t}" in defs:
            v[f"--color-{fam}-{s}"] = defs[f"--color-{fam}-{t}"]
    # pale tints become quiet dark tints, not saturated blocks
    base = defs.get(f"--color-{fam}-500")
    if base:
        v[f"--color-{fam}-50"] = f"color-mix(in srgb, {base} 12%, #141d1c)"
        v[f"--color-{fam}-100"] = f"color-mix(in srgb, {base} 20%, #141d1c)"
interactive = {"50": "#0f2626", "100": "#123230", "200": "#17403d", "300": "#1f5b55", "400": "#2a8f84",
               "500": "#2fb3a1", "600": "#3cc6b3", "700": "#5fd3c2", "800": "#86e0d3", "900": "#aeeae1"}
primary = {"50": "#0f2626", "100": "#123230", "200": "#17403d", "300": "#1f5b55", "400": "#2fb39c"}
for s, c in interactive.items():
    v[f"--color-dd-interactive-{s}"] = c
for s, c in primary.items():
    v[f"--color-dd-primary-{s}"] = c
v.update({
    "--color-ground": "#0e1514", "--color-frame": "#131c1b", "--color-surface": "#172120", "--color-surface-2": "#1b2726",
    "--color-surface-3": "#22302e", "--color-border": "#283734", "--color-border-strong": "#3a4b47",
    "--color-text": "#e3eeeb", "--color-text-muted": "#a1b4af", "--color-text-faint": "#7f938e",
    "--color-dd-on-primary": "#ffffff", "--color-dd-accent-light": "#123a35",
    "--color-dd-accent": "#5fd3c2", "--color-dd-accent-hover": "#86e0d3", "--color-dd-accent-dark": "#aeeae1",
    "--color-panel-blue": "#4fb3c8", "--color-panel-green": "#7cc35e", "--color-panel-red": "#ff7a70", "--color-panel-yellow": "#e0b64a",
    "--color-severity-critical-bg": "rgba(224,89,79,.18)", "--color-severity-critical-text": "#ff9a90",
    "--color-severity-high-bg": "rgba(249,115,22,.17)", "--color-severity-high-text": "#fdba74",
    "--color-severity-medium-bg": "rgba(234,179,8,.16)", "--color-severity-medium-text": "#fde047",
    "--color-severity-low-bg": "rgba(59,130,246,.18)", "--color-severity-low-text": "#93c5fd",
    "--color-severity-info-bg": "rgba(148,163,184,.14)", "--color-severity-info-text": "#cbd5e1",
    "--os-shadow": "0 1px 2px rgba(0,0,0,.35), 0 2px 8px rgba(0,0,0,.18)",
})
tokens = "\n".join(f"    {k}:{val};" for k, val in sorted(v.items()))

components = (Path(__file__).parent / "dark_components.css").read_text()
out = f"""{{% comment %}}
OraSec dark theme (one dark "security console" look on every page). GENERATED by scripts/dark_theme/gen_dark_theme.py from the
Tailwind palette plus scripts/dark_theme/dark_components.css; edit those and regenerate. Loaded after orasec/_theme.html.
Remove the include in base.html to return to the light theme.
{{% endcomment %}}
<meta name="color-scheme" content="dark">
<style>
  :root {{
    color-scheme: dark;
{tokens}
  }}
{components}
</style>
<script>
  // charts: readable labels and quiet grid lines on the dark surface
  document.addEventListener("DOMContentLoaded", function () {{
    if (window.Chart && Chart.defaults) {{
      var d = Chart.defaults; d.color = "#a1b4af"; d.borderColor = "rgba(255,255,255,.08)";
      if (d.global) {{ d.global.defaultFontColor = "#a1b4af"; }}
      if (d.scale && d.scale.gridLines) {{ d.scale.gridLines.color = "rgba(255,255,255,.08)"; }}
    }}
  }});
</script>
"""
(ROOT / "orasec/templates/orasec/_theme_dark.html").write_text(out)
print("written", len(out), "bytes,", len(v), "tokens")

